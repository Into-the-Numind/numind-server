#!/bin/bash

# 紧急修复效果验证脚本 - 专注传统渲染器

set -e

echo "🚨 紧急修复验证：第7条内容丢失问题..."
echo "================================================================"

# 颜色定义
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
PURPLE='\033[0;35m'
NC='\033[0m' # No Color

# 检查服务是否运行
echo -e "${BLUE}🔍 检查服务状态...${NC}"
if pgrep -f "numind" > /dev/null; then
    echo -e "${GREEN}✅ 服务正在运行${NC}"
else
    echo -e "${RED}❌ 服务未运行，请先启动服务${NC}"
    echo "启动命令: ./numind"
    exit 1
fi

echo ""

# 显示紧急修复摘要
echo -e "${PURPLE}🚨 紧急修复内容：${NC}"
echo "1. ✅ 修复传统渲染器数据结构：Content interface{} 支持数组"
echo "2. ✅ 优化超长图渲染器：180s超时 + 16GB内存 + 更多禁用功能"
echo "3. ✅ 暂时禁用增强版渲染器：优先使用修复后的传统渲染器"
echo "4. ✅ 预期结果：应该能正确渲染2张卡片，包含全部7条内容"

echo ""

echo -e "${YELLOW}⚠️ 当前策略：增强版渲染器已禁用，强制使用传统渲染器${NC}"
echo ""

# 监控关键修复日志
echo -e "${BLUE}🔧 监控传统渲染器修复效果...${NC}"
echo "正在监控以下关键指标："
echo "1. 渲染器选择：应该直接跳过增强版，使用传统版"
echo "2. 数据解析：卡片数据能否正确解析（不再有数据结构错误）"
echo "3. 分页结果：应该有2张卡片（已通过之前的分页修复）"
echo "4. 渲染成功：两张卡片都能成功渲染"

echo ""
echo -e "${YELLOW}⏳ 请在另一个窗口创建包含7条列表内容的book，然后观察以下日志...${NC}"
echo ""

# 实时监控关键日志
tail -f logs/app.log | grep -E "(使用渲染-测量方案|🔍 卡片.*包含.*个元素|🔍 元素.*类型|🔍 列表元素包含.*项|关键修复：直接使用已分页的卡片|✅ 页面.*渲染完成|✅ 渲染完成，生成.*张图片|⚠️.*生成卡片.*HTML失败)" --line-buffered | while read line; do
    case "$line" in
        *"使用渲染-测量方案"*)
            echo -e "${BLUE}🔧 渲染器策略: $line${NC}"
            ;;
        *"🔍 卡片"*"包含"*"个元素"*|*"🔍 元素"*"类型"*|*"🔍 列表元素包含"*"项"*)
            echo -e "${GREEN}📊 数据解析: $line${NC}"
            ;;
        *"关键修复：直接使用已分页的卡片"*)
            echo -e "${PURPLE}🔧 传统渲染器修复应用: $line${NC}"
            ;;
        *"✅ 页面"*"渲染完成"*|*"✅ 渲染完成，生成"*"张图片"*)
            echo -e "${GREEN}🖼️ 渲染成功: $line${NC}"
            ;;
        *"⚠️"*"生成卡片"*"HTML失败"*)
            echo -e "${RED}❌ 渲染失败: $line${NC}"
            ;;
        *)
            echo "$line"
            ;;
    esac
done
